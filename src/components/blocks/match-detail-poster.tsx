/**
 * Match-detail share poster inspired by a post-match performance recap.
 * It keeps the original MatchDetailPoster data contract while adding the
 * compact scoreboard hierarchy: summary stats, lobby benchmark bars, moments,
 * and derived performance insights.
 */
function MatchDetailPoster({
  brandLabel = 'VALPRO',
  outcomeLabel,
  result = 'win',
  myTeamScore,
  enemyTeamScore,
  mapName,
  modeLabel,
  durationLabel,
  dateLabel,
  rankLabel,
  mapBackgroundUrl,
  agentIconUrl,
  agentName,
  playerTag,
  kills,
  deaths,
  assists,
  firstDeaths,
  primaryMetrics,
  secondaryMetrics,
  comparisons,
  moments,
  insights,
  badges,
  labels,
  width = 1080,
  height = 1920,
}: MatchDetailPosterProps) {
  const accentColor = result === 'win' ? WIN_ACCENT : result === 'loss' ? LOSS_ACCENT : DRAW_ACCENT;
  const kdRatio = deaths > 0 ? (kills / deaths).toFixed(2) : '∞';
  const summaryStats: MatchDetailPosterMetric[] = [
    { label: 'K/D', value: kdRatio },
    ...primaryMetrics.filter((metric) => ['ACS', 'ADR', 'HS%', 'KAST'].includes(metric.label.toUpperCase())),
  ].slice(0, 5);
  const fallbackMoments: MatchDetailPosterMoment[] = secondaryMetrics
    .slice(0, 4)
    .map((metric) => ({
      label: metric.label,
      value: metric.value,
    }));
  const visibleMoments = moments?.length ? moments.slice(0, 4) : fallbackMoments;
  const hasComparisons = Boolean(comparisons?.length);
  const visibleInsights: MatchDetailPosterInsight[] = insights?.length
    ? insights.slice(0, 4)
    : badges?.slice(0, 4).map((badge) => {
        const normalized = normalizeBadge(badge);
        return {
          text: normalized.value === undefined ? normalized.label : `${normalized.label} ${normalized.value}`,
          tone: normalized.tone,
        };
      }) ?? [];
  const hasInsights = visibleInsights.length > 0;
  const contentWidth = width / POSTER_CONTENT_DENSITY;
  const contentHeight = height / POSTER_CONTENT_DENSITY;
  const contentOffsetX = (width - contentWidth) / 2;
  const contentOffsetY = (height - contentHeight) / 2;

  return (
    <View
      style={{
        width,
        height,
        position: 'relative',
        overflow: 'hidden',
        backgroundColor: BACKGROUND,
      }}>
      {mapBackgroundUrl ? (
        <Image
          source={mapBackgroundUrl}
          accessibilityLabel={`${mapName} background`}
          style={{ position: 'absolute', top: 0, right: 0, bottom: 0, left: 0, opacity: 0.4 }}
          contentFit="cover"
        />
      ) : null}
      <View
        pointerEvents="none"
        style={{
          position: 'absolute',
          top: 0,
          right: 0,
          bottom: 0,
          left: 0,
          backgroundColor: 'rgba(4, 8, 11, 0.38)',
        }}
      />
      <View
        pointerEvents="none"
        style={{
          position: 'absolute',
          top: height * 0.12,
          left: -width * 0.1,
          width: width * 1.2,
          height: width * 1.2,
        }}>
        <Svg width="100%" height="100%">
          <Defs>
            <RadialGradient id="matchDetailPosterGlow" cx="0.5" cy="0.5" r="0.5">
              <Stop offset="0" stopColor={accentColor} stopOpacity="0.08" />
              <Stop offset="0.5" stopColor={accentColor} stopOpacity="0.025" />
              <Stop offset="1" stopColor={accentColor} stopOpacity="0" />
            </RadialGradient>
          </Defs>
          <Rect x="0" y="0" width="100%" height="100%" fill="url(#matchDetailPosterGlow)" />
        </Svg>
      </View>
      <View
        style={{
          position: 'absolute',
          top: contentOffsetY,
          left: contentOffsetX,
          width: contentWidth,
          height: contentHeight,
          transform: [{ scale: POSTER_CONTENT_DENSITY }],
          paddingTop: 58,
          paddingRight: 76,
          paddingBottom: 58,
          paddingLeft: 76,
        }}>
        <View style={{ flexDirection: 'row', justifyContent: 'space-between', alignItems: 'flex-start' }}>
          <View>
            <Text
              style={{
                color: TEXT_PRIMARY,
                fontSize: 28,
                lineHeight: 32,
                fontWeight: '800',
                letterSpacing: 1.2,
              }}>
              {mapName}
            </Text>
            <Text
              style={{
                marginTop: 18,
                color: accentColor,
                fontSize: 30,
                lineHeight: 34,
                fontWeight: '900',
                letterSpacing: 3.4,
              }}>
              {outcomeLabel}
            </Text>
          </View>
          <View style={{ alignItems: 'flex-end' }}>
            {rankLabel ? (
              <Text
                style={{
                  color: TEXT_PRIMARY,
                  fontSize: 28,
                  lineHeight: 32,
                  fontWeight: '900',
                  letterSpacing: 1.5,
                }}>
                {rankLabel}
              </Text>
            ) : null}
            {dateLabel ? (
              <Text
                style={{
                  marginTop: 14,
                  color: TEXT_MUTED,
                  fontSize: 22,
                  lineHeight: 26,
                  fontWeight: '700',
                }}>
                {dateLabel}
              </Text>
            ) : null}
          </View>
        </View>

        <View
          style={{
            marginTop: 38,
            flexDirection: 'row',
            alignItems: 'center',
          }}>
          <Text
            style={{
              flexShrink: 0,
              color: result === 'win' ? accentColor : TEXT_PRIMARY,
              fontSize: 190,
              lineHeight: 174,
              fontWeight: '900',
              letterSpacing: -15,
              fontVariant: ['tabular-nums'],
              textAlign: 'left',
            }}>
            {myTeamScore}
          </Text>
          <Text
            style={{
              flexShrink: 0,
              marginHorizontal: 12,
              color: TEXT_PRIMARY,
              opacity: 0.3,
              fontSize: 92,
              lineHeight: 174,
              fontWeight: '300',
            }}>
            -
          </Text>
          <Text
            style={{
              flexShrink: 0,
              color: result === 'loss' ? accentColor : TEXT_PRIMARY,
              opacity: result === 'loss' ? 1 : 0.48,
              fontSize: 190,
              lineHeight: 174,
              fontWeight: '900',
              letterSpacing: -15,
              fontVariant: ['tabular-nums'],
              textAlign: 'left',
            }}>
            {enemyTeamScore}
          </Text>
        </View>
        <Text
          style={{
            marginTop: 2,
            marginBottom: 26,
            color: TEXT_MUTED,
            fontSize: 18,
            lineHeight: 22,
            fontWeight: '800',
            letterSpacing: 3.7,
          }}>
          {mapName.toUpperCase()} {'·'} {modeLabel.toUpperCase()} {'·'} {durationLabel}
        </Text>

        <View
          style={{
            flexDirection: 'row',
            alignItems: 'center',
            paddingVertical: 16,
            paddingHorizontal: 20,
            marginBottom: 24,
            borderRadius: 22,
            backgroundColor: 'rgba(12, 16, 18, 0.64)',
            borderWidth: 1,
            borderColor: 'rgba(255, 255, 255, 0.14)',
          }}>
          <Image
            source={agentIconUrl}
            accessibilityLabel={agentName}
            style={{ width: 82, height: 82, borderRadius: 18, backgroundColor: withAlpha(accentColor, 0.2) }}
            contentFit="cover"
          />
          <View style={{ flex: 1, marginLeft: 16 }}>
            <View style={{ flexDirection: 'row', alignItems: 'baseline', gap: 8 }}>
              <Text style={{ color: TEXT_PRIMARY, fontSize: 34, lineHeight: 38, fontWeight: '900' }}>
                {playerTag.split('#')[0]}
              </Text>
              {playerTag.includes('#') ? (
                <Text style={{ color: TEXT_MUTED, fontSize: 22, lineHeight: 26, fontWeight: '600' }}>
                  #{playerTag.split('#').slice(1).join('#')}
                </Text>
              ) : null}
            </View>
            <Text
              style={{
                marginTop: 5,
                color: TEXT_MUTED,
                fontSize: 21,
                lineHeight: 25,
                fontWeight: '700',
                letterSpacing: 1,
              }}>
              {agentName}
            </Text>
          </View>
          <Text
            style={{
              color: TEXT_PRIMARY,
              fontSize: 58,
              lineHeight: 62,
              fontWeight: '800',
              fontVariant: ['tabular-nums'],
            }}>
            {kills}/{deaths}/{assists}
          </Text>
        </View>

        <SummaryCard stats={summaryStats} />

        <View style={{ flex: 1, justifyContent: 'flex-end', marginTop: 24 }}>
          {hasComparisons ? (
            <View style={{ marginBottom: 24 }}>
              <SectionLabel>{labels?.vsLobby ?? 'VS. LOBBY'}</SectionLabel>
              <ComparisonCard comparisons={comparisons!} />
            </View>
          ) : null}

          {visibleMoments.length > 0 ? (
            <View style={{ marginBottom: hasInsights ? 24 : 0 }}>
              <SectionLabel>{labels?.matchMoments ?? 'MATCH MOMENTS'}</SectionLabel>
              <View style={{ flexDirection: 'row', gap: 12 }}>
                {visibleMoments.slice(0, 2).map((moment, index) => (
                  <MomentCard key={`${moment.label}-${index}`} moment={moment} accentColor={accentColor} />
                ))}
              </View>
              {visibleMoments.length > 2 ? (
                <View style={{ flexDirection: 'row', gap: 12, marginTop: 12 }}>
                  {visibleMoments.slice(2, 4).map((moment, index) => (
                    <MomentCard key={`${moment.label}-${index + 2}`} moment={moment} accentColor={accentColor} />
                  ))}
                </View>
              ) : null}
            </View>
          ) : null}

          {hasInsights ? (
            <View style={{ flexDirection: 'row', flexWrap: 'wrap', gap: 12 }}>
              {visibleInsights.map((insight, index) => {
                const insightColor = insight.color ?? getBadgeColor(insight.tone, accentColor);
                return (
                  <View
                    key={`${insight.text}-${index}`}
                    style={{
                      paddingVertical: 11,
                      paddingHorizontal: 16,
                      borderRadius: 999,
                      backgroundColor: withAlpha(insightColor, 0.16),
                      borderWidth: 1,
                      borderColor: withAlpha(insightColor, 0.58),
                    }}>
                    <Text
                      style={{
                        color: insightColor,
                        fontSize: 17,
                        lineHeight: 21,
                        fontWeight: '800',
                        letterSpacing: 1.2,
                      }}>
                      {insight.text}
                    </Text>
                  </View>
                );
              })}
            </View>
          ) : null}

          <View
            style={{
              flexDirection: 'row',
              flexShrink: 0,
              justifyContent: 'flex-end',
              alignItems: 'center',
              marginTop: 20,
            }}>
            <BrandMark label={brandLabel} size={29} />
          </View>
        </View>
      </View>
    </View>
  );
}

