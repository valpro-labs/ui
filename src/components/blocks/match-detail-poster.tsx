import * as React from 'react';

import { View } from 'react-native';

import { BrandMark } from '@/components/blocks/brand-mark';
import { Image } from '@/components/ui/image';
import { Text } from '@/components/ui/text';
import { Defs, RadialGradient, Rect, Stop, Svg } from '@/lib/svg-shim';

type MatchDetailPosterMetric = {
  label: string;
  value: string | number;
  delta?: string;
};

type MatchDetailPosterComparison = {
  label: string;
  value: string | number;
  delta: string;
  /** Filled portion of the comparison bar, from 0 to 100. */
  playerPercent: number;
  /** Benchmark marker position, from 0 to 100. */
  benchmarkPercent: number;
};

type MatchDetailPosterMoment = {
  /** Deprecated visual hint kept for backwards compatibility; the poster uses a typographic marker. */
  icon?: string;
  label: string;
  value: string | number;
  description?: string;
  /** Deprecated image slot kept for backwards compatibility. */
  imageUrl?: string;
};

type MatchDetailPosterBadgeTone = 'positive' | 'negative' | 'neutral' | 'accent';

type MatchDetailPosterBadge = {
  label: string;
  value?: string | number;
  tone?: MatchDetailPosterBadgeTone;
};

type MatchDetailPosterInsight = {
  /** Conclusion text shown in the insight pill. */
  text: string;
  /** Optional explicit color, e.g. rgb(34, 255, 197) or #22ffc5. */
  color?: string;
  /** Optional semantic fallback when color is not provided. */
  tone?: MatchDetailPosterBadgeTone;
};

type MatchDetailPosterLabels = {
  /** Section title for lobby comparisons. */
  vsLobby?: string;
  /** Section title for match moments. */
  matchMoments?: string;
};

type MatchDetailPosterProps = {
  /** Footer brand wordmark rendered with the shared VALPRO brand-mark logic. */
  brandLabel?: string;
  /** Match result callout, e.g. `"VICTORY"`. */
  outcomeLabel: string;
  /** Matches MatchCard result semantics: win, loss, or a neutral draw. */
  result?: 'win' | 'loss' | 'draw';
  /** Left score in the hero row. */
  myTeamScore: number;
  /** Right score in the hero row. */
  enemyTeamScore: number;
  /** Map / mode / duration line under the score. */
  mapName: string;
  modeLabel: string;
  durationLabel: string;
  /** Optional date shown in the top-right metadata block. */
  dateLabel?: string;
  /** Optional rank / queue label shown above the date. */
  rankLabel?: string;
  /** Optional map splash art rendered behind the poster content. */
  mapBackgroundUrl?: string;
  /** Kept for backwards compatibility. The new layout uses the agent icon. */
  agentPortraitUrl?: string;
  /** Small agent icon shown beside the player identity. */
  agentIconUrl: string;
  /** Agent display name in the player identity block. */
  agentName: string;
  /** Player name/tag shown in the player identity block. */
  playerTag: string;
  /** Highlight KDA block. */
  kills: number;
  deaths: number;
  assists: number;
  /** First deaths, sourced from the match combat stats (`FD`). */
  firstDeaths?: number;
  /** Core metric row, typically ACS / ADR / HS% / KAST. */
  primaryMetrics: MatchDetailPosterMetric[];
  /** Additional metrics retained for existing callers and moment fallbacks. */
  secondaryMetrics: MatchDetailPosterMetric[];
  /** Optional benchmark rows. When omitted, the comparison panel is hidden. */
  comparisons?: MatchDetailPosterComparison[];
  /** Optional highlight cards, based on the app's match moments / multikills. */
  moments?: MatchDetailPosterMoment[];
  /** Optional conclusion labels. These are preferred over raw stat badges. */
  insights?: MatchDetailPosterInsight[];
  /** Backwards-compatible raw badge input; converted to compact conclusions when insights is absent. */
  badges?: Array<MatchDetailPosterBadge | string>;
  /** Optional translations for labels generated by the poster itself. */
  labels?: MatchDetailPosterLabels;
  /** Override the default 1080px canvas width. */
  width?: number;
  /** Override the default 1920px canvas height. */
  height?: number;
};

const BACKGROUND = 'rgb(8, 14, 18)';
const TEXT_PRIMARY = 'rgb(237, 233, 226)';
const TEXT_MUTED = 'rgba(237, 233, 226, 0.62)';
const VALPRO_RED = 'rgb(255, 70, 85)';
const WIN_ACCENT = 'rgb(34, 255, 197)';
const LOSS_ACCENT = VALPRO_RED;
const DRAW_ACCENT = 'rgb(240, 203, 116)';
const CARD_BACKGROUND = 'rgba(21, 24, 26, 0.72)';
const POSTER_CONTENT_DENSITY = 1.1;

function withAlpha(color: string, alpha: number): string {
  if (color.startsWith('rgb(')) {
    return color.replace('rgb(', 'rgba(').replace(')', `, ${alpha})`);
  }

  if (/^#[0-9a-f]{6}$/i.test(color)) {
    const red = Number.parseInt(color.slice(1, 3), 16);
    const green = Number.parseInt(color.slice(3, 5), 16);
    const blue = Number.parseInt(color.slice(5, 7), 16);
    return `rgba(${red}, ${green}, ${blue}, ${alpha})`;
  }

  return color;
}

function clampPercent(value: number): number {
  return Math.min(100, Math.max(0, value));
}

function getDeltaColor(delta: string): string {
  if (delta.startsWith('+')) return WIN_ACCENT;
  if (delta.startsWith('-')) return VALPRO_RED;
  return DRAW_ACCENT;
}

function normalizeBadge(badge: MatchDetailPosterBadge | string): MatchDetailPosterBadge {
  return typeof badge === 'string' ? { label: badge, tone: 'neutral' } : badge;
}

function getBadgeColor(tone: MatchDetailPosterBadgeTone = 'neutral', accentColor: string): string {
  if (tone === 'positive') return WIN_ACCENT;
  if (tone === 'negative') return VALPRO_RED;
  if (tone === 'accent') return accentColor;
  return DRAW_ACCENT;
}

function ComparisonBar({
  playerPercent,
  benchmarkPercent,
}: {
  playerPercent: number;
  benchmarkPercent: number;
}) {
  const player = clampPercent(playerPercent);
  const benchmark = clampPercent(benchmarkPercent);
  const isAhead = player > benchmark;
  const isBehind = player < benchmark;

  return (
    <View
      style={{
        flex: 1,
        height: 20,
        position: 'relative',
        overflow: 'hidden',
        borderRadius: 999,
        backgroundColor: 'rgba(255, 255, 255, 0.15)',
      }}>
      <View
        style={{
          position: 'absolute',
          top: 0,
          bottom: 0,
          left: 0,
          width: `${player}%`,
          borderRadius: 999,
          backgroundColor: isAhead ? WIN_ACCENT : isBehind ? VALPRO_RED : DRAW_ACCENT,
          opacity: 0.82,
        }}
      />
      <View
        style={{
          position: 'absolute',
          top: -3,
          bottom: -3,
          left: `${benchmark}%`,
          width: 4,
          borderRadius: 2,
          backgroundColor: TEXT_PRIMARY,
        }}
      />
    </View>
  );
}

function SectionLabel({ children }: { children: React.ReactNode }) {
  return (
    <Text
      style={{
        marginBottom: 14,
        color: TEXT_MUTED,
        fontSize: 20,
        lineHeight: 24,
        fontWeight: '800',
        letterSpacing: 4.4,
      }}>
      {children}
    </Text>
  );
}

function SummaryCard({
  stats,
}: {
  stats: MatchDetailPosterMetric[];
}) {
  return (
    <View
      style={{
        borderRadius: 28,
        overflow: 'hidden',
        backgroundColor: CARD_BACKGROUND,
        borderWidth: 1,
        borderColor: 'rgba(255, 255, 255, 0.16)',
      }}>
      <View style={{ flexDirection: 'row', paddingVertical: 24, paddingHorizontal: 16 }}>
        {stats.map((stat, index) => (
          <View
            key={`${stat.label}-${index}`}
            style={{
              flex: 1,
              alignItems: 'center',
              justifyContent: 'center',
              borderLeftWidth: index === 0 ? 0 : 1,
              borderLeftColor: 'rgba(255, 255, 255, 0.15)',
            }}>
            <Text
              style={{
                color: TEXT_PRIMARY,
                fontSize: 42,
                lineHeight: 46,
                fontWeight: '800',
                letterSpacing: -1.4,
                fontVariant: ['tabular-nums'],
              }}>
              {stat.value}
            </Text>
            <Text
              style={{
                marginTop: 5,
                color: TEXT_MUTED,
                fontSize: 15,
                lineHeight: 18,
                fontWeight: '600',
                letterSpacing: 2.2,
              }}>
              {stat.label}
            </Text>
          </View>
        ))}
      </View>
    </View>
  );
}

function ComparisonCard({
  comparisons,
}: {
  comparisons: MatchDetailPosterComparison[];
}) {
  return (
    <View
      style={{
        paddingVertical: 24,
        paddingHorizontal: 26,
        borderRadius: 28,
        backgroundColor: 'rgba(21, 24, 26, 0.66)',
        borderWidth: 1,
        borderColor: 'rgba(255, 255, 255, 0.15)',
      }}>
      {comparisons.map((comparison, index) => (
        <View
          key={`${comparison.label}-${index}`}
          style={{
            flexDirection: 'row',
            alignItems: 'center',
            minHeight: 54,
            marginBottom: index === comparisons.length - 1 ? 0 : 8,
          }}>
          <Text
            style={{
              width: 82,
              color: TEXT_MUTED,
              fontSize: 18,
              lineHeight: 22,
              fontWeight: '600',
              letterSpacing: 1.2,
            }}>
            {comparison.label}
          </Text>
          <View style={{ flex: 1, flexDirection: 'row', alignItems: 'center', gap: 12 }}>
            <ComparisonBar
              playerPercent={comparison.playerPercent}
              benchmarkPercent={comparison.benchmarkPercent}
            />
            <Text
              style={{
                width: 70,
                color: TEXT_PRIMARY,
                textAlign: 'right',
                fontSize: 22,
                lineHeight: 26,
                fontWeight: '800',
                fontVariant: ['tabular-nums'],
              }}>
              {comparison.value}
            </Text>
            <Text
              style={{
                width: 68,
                color: getDeltaColor(comparison.delta),
                textAlign: 'right',
                fontSize: 19,
                lineHeight: 23,
                fontWeight: '600',
                fontVariant: ['tabular-nums'],
              }}>
              {comparison.delta}
            </Text>
          </View>
        </View>
      ))}
    </View>
  );
}

